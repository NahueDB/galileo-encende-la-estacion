export const VERSION = '1.0.0';
export type Check = { label: string; pass: boolean; detail?: string };
export type Snapshot = { text: string; value: string; selected: boolean; running: boolean };
export type RunResult = { checks: Check[]; pass: boolean; error?: string };
export type GameEvent = {
  id: string;
  gameId: string;
  level: number;
  version: string;
  type: 'start' | 'enter' | 'run' | 'hint' | 'complete' | 'finish';
  at: string;
  attempt: number;
  hint?: number;
  result?: RunResult;
  code?: string;
};
export type Game = {
  id: string;
  version: string;
  pair: [string, string];
  course: string;
  mode: 'demo' | 'real';
  token?: string;
  started: string;
  level: number;
  completed: number[];
  codes: Record<number, string[]>;
  hints: Record<number, number[]>;
  attempts: Record<number, number>;
  events: GameEvent[];
  pending: GameEvent[];
  finished: boolean;
};
export type Level = {
  id: number;
  version: string;
  title: string;
  concept: string;
  objective: string;
  html: string;
  prefix: string;
  zones: { label: string; initial: string; rows: number }[];
  joins?: string[];
  suffix: string;
  hints: [string, string, string];
  required: string[];
  visual: string;
  tests: string[];
};
